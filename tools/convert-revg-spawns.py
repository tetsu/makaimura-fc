#!/usr/bin/env python3
"""Convert the Revision G section 0 enemy placement to FC tables (src/revg-section0-spawns.inc).

Reads what tools/mame/extract-revg-stages.py writes (build/revg-stages: enemies.json,
sections.json, world.json; docs/revision-g-stage-data.md explains the arcade tables):

- The enemies placed at the start of the section (crows, plants, the Red Arremer) and
  the support objects (the touch triggers: discs, the hidden armour and 10,000 points).
  The tombstones are drawn in the BG and the path platform is the raft, so they are
  left out.
- The enemy group of each page, its entries (type, pattern, flags), and the records of
  every pattern the groups use (X, Y, variant, wait).

The FC kinds are the ones src/revg-enemies.inc uses.
"""

import argparse
import json
from pathlib import Path

# Arcade enemy type -> FC object kind (src/revg-enemies.inc / revg-enemies2.inc / revg-enemies34.inc).
KINDS = {
    0x00: "ok_pig", 0x01: "ok_crow", 0x02: "ok_devil", 0x03: "ok_knight",
    0x04: "ok_flyer", 0x05: "ok_arremer", 0x06: "ok_satan", 0x07: "ok_magician",
    0x08: "ok_unicorn", 0x09: "ok_skull", 0x0A: "ok_bigman", 0x0B: "ok_zombie",
    0x0C: "ok_dragon", 0x0D: "ok_astaroth", 0x0E: "ok_fire",
    0x11: "ok_plant", 0x12: "ok_pillar",
}
# The scheduler of each type a group can start (one pattern at a time per type).
SCHEDULED_BY_SECTION = {
    0: [0x0B, 0x03, 0x00, 0x08],
    1: [0x02, 0x04, 0x01, 0x08, 0x0B],
    2: [0x00, 0x04, 0x05, 0x0B, 0x0C],
    3: [0x02, 0x0C],
    4: [0x00, 0x02],
    5: [0x00, 0x05, 0x08, 0x0A, 0x0C],
    6: [],
}


def word(values, name):
    if not values:
        return [f"{name}_lo:", f"{name}_hi:"]
    return [f"{name}_lo: .byte " + ", ".join(f"<{v & 0xFFFF}" for v in values),
            f"{name}_hi: .byte " + ", ".join(f">{v & 0xFFFF}" for v in values)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, nargs="?", default=Path("src/revg-section0-spawns.inc"))
    parser.add_argument("--stages", type=Path, default=Path("build/revg-stages"))
    parser.add_argument("--section", type=int, default=0)
    parser.add_argument("--prefix", default="revg")
    args = parser.parse_args()
    enemies = json.loads((args.stages / "enemies.json").read_text())
    section = json.loads((args.stages / "sections.json").read_text())[args.section]
    world = json.loads((args.stages / "world.json").read_text())
    first, last = section["pages"]["columns"]
    row_lo, row_hi = section["pages"]["rows"]
    x_min = section["camera"]["x_min"]
    y_min = section["camera"]["y_min"]
    scheduled = SCHEDULED_BY_SECTION[args.section]
    p = args.prefix
    pages = {pg["page"]: pg for pg in world["pages"]}
    groups = {g["group"]: g for g in enemies["groups"]}
    patterns = {(pat["type"], pat["pattern"]): pat for pat in enemies["patterns"]}

    lines = [f"; Generated by tools/convert-revg-spawns.py from Revision G section {args.section}.", ""]
    fixed = [e for e in section["enemy_list"] if e["type"] in KINDS]
    lines.append(f"{p}_fix_count = {len(fixed)}")
    lines.append(f"{p}_fix_kind: .byte " + ", ".join(KINDS[e["type"]] for e in fixed))
    lines.append(f"{p}_fix_var: .byte " + ", ".join(str(e["variant"]) for e in fixed))
    lines += word([e["x"] - x_min for e in fixed], f"{p}_fix_x") + word([e["y"] - y_min for e in fixed], f"{p}_fix_y")
    support = [s for s in section["support_list"] if s["type"] == 0 and s["x"] >= x_min and s["y"] >= y_min]
    lines.append(f"{p}_sup_count = {len(support)}")
    lines.append(f"{p}_sup_var:" + (" .byte " + ", ".join(str(s["variant"]) for s in support) if support else ""))
    lines += word([s["x"] - x_min for s in support], f"{p}_sup_x") + word([s["y"] - y_min for s in support], f"{p}_sup_y")
    lines.append("")

    # Patterns: the records in one list, each pattern a start and a count.
    used, records = [], []
    entries = []                    # per page: up to 3 (scheduler, pattern index, flags)
    page_list = [r * 32 + c for r in range(row_lo, row_hi + 1) for c in range(first, last + 1)]
    for page in page_list:
        row = []
        for e in groups[pages[page]["group"]]["entries"]:
            if e["type"] not in scheduled:
                raise SystemExit(f"page {page}: type {e['type']} has no FC scheduler")
            key = (e["type"], e["pattern"])
            if key not in used:
                used.append(key)
            row.append((scheduled.index(e["type"]), used.index(key), e["flags"]))
        entries.append(row)
    starts, counts = [], []
    for key in used:
        starts.append(len(records))
        counts.append(len(patterns[key]["records"]))
        for rec in patterns[key]["records"]:
            rec_copy = dict(rec)
            # World-coordinate records (in patterns with flags bit 0 = 1) have arcade X >= x_min.
            if rec_copy["x"] >= x_min and x_min > 0:
                rec_copy["x"] -= x_min
            records.append(rec_copy)
    lines.append(f"{p}_page_cols = {last - first + 1}")
    lines.append(f"{p}_page_rows = {row_hi - row_lo + 1}")
    lines.append(f"{p}_page_count = {len(page_list)}")
    lines.append("; Per page: up to three group entries (scheduler + 1, pattern, flags); 0 ends.")
    lines.append(f"{p}_page_groups:")
    for page, row in zip(page_list, entries):
        flat = []
        for sched, pattern, flags in row:
            flat += [sched + 1, pattern, flags]
        flat += [0] * (9 - len(flat))
        lines.append(f"    .byte {', '.join(map(str, flat))}   ; page {page:#05x}")
    lines.append("; Schedulers: " + ", ".join(f"{i} {KINDS[t]}" for i, t in enumerate(scheduled)))
    lines.append(f"{p}_sched_kind:" + (" .byte " + ", ".join(KINDS[t] for t in scheduled) if scheduled else ""))
    lines.append(f"{p}_pat_start:" + (" .byte " + ", ".join(map(str, starts)) if starts else ""))
    lines.append(f"{p}_pat_count:" + (" .byte " + ", ".join(map(str, counts)) if counts else ""))
    lines += word([r["x"] for r in records], f"{p}_rec_x") + word([r["y"] for r in records], f"{p}_rec_y")
    lines.append(f"{p}_rec_var:" + (" .byte " + ", ".join(str(r["variant"]) for r in records) if records else ""))
    lines.append(f"{p}_rec_wait:" + (" .byte " + ", ".join(str(r["wait"]) for r in records) if records else ""))
    args.output.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"{args.output}: {len(fixed)} placed enemies, {len(support)} triggers, "
          f"{len(used)} patterns, {len(records)} records")


if __name__ == "__main__":
    main()
